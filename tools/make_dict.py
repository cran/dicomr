#!/usr/bin/env python3
"""Generate src/dict_data.h from pydicom's MIT-licensed data dictionary.

Usage: python3 tools/make_dict.py   (run from the package root)
The dictionary in pydicom is itself generated from the DICOM Standard (PS3.6).
"""
import json
from pydicom._dicom_dict import DicomDictionary, RepeatersDictionary
import pydicom

def cstr(s):
    return json.dumps(s)  # JSON string escaping is valid C string escaping for ASCII

lines = []
lines.append("// Auto-generated by tools/make_dict.py from pydicom %s (MIT License)." % pydicom.__version__)
lines.append("// Source: pydicom/_dicom_dict.py, generated from DICOM PS3.6. Do not edit by hand.")
lines.append("#ifndef DICOMR_DICT_DATA_H\n#define DICOMR_DICT_DATA_H\n#include <cstdint>")
lines.append("struct DictEntry { uint32_t tag; const char* vr; const char* vm; const char* name; const char* retired; const char* keyword; };")
lines.append("struct RepeaterEntry { const char* mask; const char* vr; const char* vm; const char* name; const char* retired; const char* keyword; };")
lines.append("static const DictEntry DICOM_DICT[] = {")
for tag in sorted(DicomDictionary):
    vr, vm, name, ret, kw = DicomDictionary[tag]
    lines.append("  {0x%08XU, %s, %s, %s, %s, %s}," % (tag, cstr(vr), cstr(vm), cstr(name), cstr(ret), cstr(kw)))
lines.append("};")
lines.append("static const int DICOM_DICT_N = %d;" % len(DicomDictionary))
lines.append("static const RepeaterEntry DICOM_REPEATERS[] = {")
for mask in sorted(RepeatersDictionary):
    vr, vm, name, ret, kw = RepeatersDictionary[mask]
    lines.append("  {%s, %s, %s, %s, %s, %s}," % (cstr(mask.upper()), cstr(vr), cstr(vm), cstr(name), cstr(ret), cstr(kw)))
lines.append("};")
lines.append("static const int DICOM_REPEATERS_N = %d;" % len(RepeatersDictionary))
lines.append("#endif")
open("src/dict_data.h", "w").write("\n".join(lines) + "\n")
print("wrote", len(DicomDictionary), "entries and", len(RepeatersDictionary), "repeaters")
